// Long Haul – turns the campaign master (story/campaign/Long_Haul_Full_Campaign.md) into js/campaign/script.js.
// Run after editing the master:  node tools/build-campaign.mjs
// The master stays the source of truth: line ids, speakers, directions and wording are copied exactly, so recorded
// takes (named by line id) match what the game plays.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const SRC = here("../story/campaign/Long_Haul_Full_Campaign.md");
const OUT = here("../js/campaign/script.js");

export function parseCampaign(md) {
  const chapters = [], runtime = [];
  let chapter = null, mission = null, scene = null, branch = null, section = null;
  const paras = md.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  for (const p of paras) {
    let m;
    if ((m = /^# CHAPTER (\d+) - (.+)$/.exec(p))) {
      chapter = { n: Number(m[1]), title: titleCase(m[2]), intro: "", missions: [] };
      chapters.push(chapter); mission = scene = null; section = null;
      continue;
    }
    if (/^# RUNTIME DIALOGUE/.test(p)) { chapter = mission = scene = null; section = "runtime"; continue; }
    if (/^# /.test(p)) { chapter = mission = scene = null; section = null; continue; }
    if ((m = /^## (\d\d\.\d\d) - (.+)$/.exec(p)) && chapter) {
      mission = { id: m[1], title: m[2], chapter: chapter.n, target: 0, location: "", unlock: "", objectives: "", gameplay: "", success: "", recovery: "", choice: "", notes: [], scenes: [] };
      chapter.missions.push(mission); scene = null;
      continue;
    }
    if ((m = /^## (R\.\d\d) - (.+)$/.exec(p)) && section === "runtime") {
      mission = { id: m[1], title: m[2], scenes: [] }; runtime.push(mission); scene = null;
      continue;
    }
    if ((m = /^### SCENE ([A-Z]) - (.+?)(?: \| (.+))?$/.exec(p)) && mission) {
      scene = { key: mission.id + "." + m[1], title: m[2], kind: m[3] || "", stage: "", notes: [], lines: [], journal: "" };
      mission.scenes.push(scene); branch = null;
      continue;
    }
    if ((m = /^(LH-[A-Z0-9-]+) \| ([A-Z]+) \[([^\]]*)\]: (.+)$/.exec(p))) {
      if (!scene) throw new Error("Line outside a scene: " + m[1]);
      const line = { id: m[1], sp: m[2], dir: m[3], text: m[4] };
      const cond = /\bif ([^;]+)/.exec(m[3]);
      if (cond) line.cond = cond[1].trim();
      if (branch) line.branch = branch;
      // a choice can also be named at the head of the direction: "[ASK_COPY]", "[RAM; shouting]"
      const head = /^([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*)(?:;|$)/.exec(m[3]);
      if (head && !line.branch) line.branch = head[1];
      scene.lines.push(line);
      continue;
    }
    if (scene && (m = /^(?:Branch|Choice) ([A-Z_]+):/.exec(p))) { branch = m[1]; if (!/:$/.test(p)) scene.notes.push(p); continue; }
    if (scene && p === "Shared:") { branch = null; continue; }
    if (scene && (m = /^Mission journal: '(.+)'$/.exec(p))) { scene.journal = m[1]; continue; }
    if (mission && !scene && chapter) {
      const f = /^(Target|Route|Objectives|Gameplay|Success|Recovery|Choice|Choices): (.+)$/.exec(p);
      if (f) {
        const k = f[1].toLowerCase();
        if (k === "target" || k === "route") {
          const t = /(\d+) minutes/.exec(p); if (t) mission.target = Number(t[1]);
          const loc = /(?:Location|Route): ([^.]+(?:\.\d+[^.]*)?)\./.exec(p); if (loc) mission.location = loc[1].trim();
          const un = /(?:Unlock|Requires) ([^.]+)\./.exec(p.replace("Unlock:", "Unlock")); if (un) mission.unlock = un[1].replace(/^: /, "").trim();
        } else mission[k === "choices" ? "choice" : k] = f[2];
        continue;
      }
      mission.notes.push(p);
      continue;
    }
    if (scene) { if (!scene.stage && !scene.lines.length) scene.stage = p; else scene.notes.push(p); continue; }
    if (chapter && !mission && !chapter.intro) { chapter.intro = p; continue; }
  }
  return { chapters, runtime };
}

function titleCase(s) {
  return s.toLowerCase().replace(/(^|[\s-])([a-z])/g, (all, a, b) => a + b.toUpperCase()).replace(/\b(A|The|On|Of|To)\b(?!$)/g, (w, x, i) => (i ? w.toLowerCase() : w));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = parseCampaign(readFileSync(SRC, "utf8"));
  const lines = [...data.chapters.flatMap((c) => c.missions), ...data.runtime].flatMap((m) => m.scenes).reduce((n, s) => n + s.lines.length, 0);
  const js = `// Long Haul – THE RETURN TRIP campaign script. GENERATED by tools/build-campaign.mjs from
// story/campaign/Long_Haul_Full_Campaign.md – edit the master and rebuild, never this file.
// ${data.chapters.length} chapters, ${data.chapters.reduce((n, c) => n + c.missions.length, 0)} missions, ${lines} spoken lines (ids match the recording manifest).
export const SCRIPT = ${JSON.stringify(data)};
`;
  writeFileSync(OUT, js);
  console.log(`Wrote ${OUT}: ${data.chapters.length} chapters, ${lines} lines`);
}
